#!/usr/bin/env python3
"""Generate tokens/llm/token-catalog.json: every token path, its type, resolved value
and category. verify_all.py regenerates it in memory and fails on drift.
Run: python3 tokens/build_catalog.py [--check]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokens_lib as T

OUT = os.path.join(T.TOKENS, "llm", "token-catalog.json")

CATEGORY = {
    "foundation.color": "color", "foundation.font.family": "fontFamily", "foundation.font.weight": "fontWeight",
    "foundation.font.size": "fontSize", "foundation.font.lineHeight": "lineHeight", "foundation.font.letterSpacing": "letterSpacing",
    "foundation.space": "spacing", "foundation.radius": "radius", "foundation.breakpoint": "breakpoint",
    "foundation.shadow": "elevation", "foundation.dropShadow": "elevation", "foundation.blur": "blur", "foundation.saturate": "blur",
    "foundation.gradient": "gradient", "foundation.duration": "motion", "foundation.easing": "motion", "foundation.delay": "motion",
    "foundation.distance": "motion", "foundation.scale": "motion", "foundation.opacity": "motion", "foundation.rotate": "motion",
    "foundation.keyframes": "motion", "foundation.particles": "motion", "foundation.observer": "motion",
    "foundation.iconSize": "iconSize", "zIndex": "zIndex", "container": "layout", "sectionPadding": "layout",
    "color": "semanticColor", "radius": "semanticShape", "elevation": "semanticShape", "blur": "semanticShape", "space": "semanticSpace",
}


def category(path):
    best = ""
    for p, c in CATEGORY.items():
        if (path == p or path.startswith(p + ".")) and len(p) > len(best):
            best = p
    return CATEGORY.get(best, "other")


def build():
    tree, _ = T.load_tree()
    tokens = {}
    for path, node in T.walk_tokens(tree):
        tokens[path] = {
            "category": category(path),
            "type": node.get("$type", "reference"),
            "value": T.resolve_value(tree, node),
        }
    counts = {}
    for t in tokens.values():
        counts[t["category"]] = counts.get(t["category"], 0) + 1
    typography = sorted(tree["typography"])
    recipes = sorted(tree["motion"]["recipe"])
    return {
        "version": "1.0.0",
        "$comment": "GENERATED by tokens/build_catalog.py. Do not hand-edit.",
        "counts": {"tokens": len(tokens), "byCategory": dict(sorted(counts.items())), "typographyRoles": len(typography), "motionRecipes": len(recipes)},
        "typographyRoles": typography,
        "motionRecipes": recipes,
        "tokens": dict(sorted(tokens.items())),
    }


if __name__ == "__main__":
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("catalog up to date" if ok else "catalog OUT OF DATE")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print("wrote tokens/llm/token-catalog.json")
