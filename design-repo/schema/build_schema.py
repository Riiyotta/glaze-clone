#!/usr/bin/env python3
"""Generate schema/pagespec.schema.json from sections/*.json and templates/templates.json.

The schema is a build output: edit the section contracts, then run this script.
extraction/verify_all.py regenerates the schema in memory and fails if the file on
disk differs, so the two cannot drift. Run: python3 schema/build_schema.py [--check]
"""
import glob, json, os, sys

DR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(DR, "schema", "pagespec.schema.json")
# PageSpec contract version: major = a PageSpec-breaking change (2.0.0 added the required `mode`). Machine-checked against registry.manifest.json pageSpecVersion.
PAGESPEC_VERSION = "2.0.0"


def build():
    sections = {}
    for f in sorted(glob.glob(os.path.join(DR, "sections", "*.json"))):
        d = json.load(open(f))
        sections[d["typeId"]] = d
    templates = json.load(open(os.path.join(DR, "templates", "templates.json")))["templates"]
    assets = json.load(open(os.path.join(DR, "assets", "asset-roles.json")))
    branches = []
    for tid in sorted(sections):
        s = sections[tid]
        branches.append({
            "if": {"properties": {"type": {"const": tid}}, "required": ["type"]},
            "then": {"properties": {
                "content": s["contentModel"],
                "motion": {"properties": {"pattern": {"enum": s["motion"]["allowedPatterns"]}}},
                # retrieval eligibility is pinned per section type: a node may omit the flag, but may
                # never state a value that differs from its section contract
                "retrievalEligible": {"const": s.get("retrievalEligible")},
            }},
        })
    schema = {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$id": "pagespec.schema.json",
        "$comment": "GENERATED by schema/build_schema.py from sections/*.json. Do not hand-edit.",
        "version": PAGESPEC_VERSION,
        "title": "Glaze design-repo PageSpec (mode: reference | generated)",
        "type": "object",
        "additionalProperties": False,
        "required": ["id", "mode", "route", "template", "theme", "nodes"],
        "properties": {
            "id": {"type": "string", "pattern": "^page\\.[a-z0-9-]+$"},
            "mode": {"enum": ["reference", "generated"], "description": "reference = a page for the SOURCE brand (all roles incl. reference-only); generated = a new page for any other brand (generation-safe roles only, no source brand, copy, URLs or assets). Required, closed."},
            "route": {"type": "string", "pattern": "^/[A-Za-z0-9/*_-]*$"},
            "template": {"enum": sorted(templates)},
            "theme": {"enum": ["dark"]},
            "head": {"$ref": "#/definitions/head"},
            "nodes": {"type": "array", "minItems": 2, "maxItems": 90, "items": {"$ref": "#/definitions/node"}},
        },
        "definitions": {
            "head": {
                "type": "object", "additionalProperties": False, "required": ["title"],
                "properties": {"title": {"type": "string", "maxWords": 18}, "description": {"type": "string", "maxWords": 30}, "robots": {"enum": ["max-image-preview:large", "noindex"]}},
            },
            "motion": {
                "type": "object", "additionalProperties": False,
                "required": ["pattern", "reducedMotionFallback"],
                "properties": {
                    "pattern": {"type": "string"},
                    "delayMs": {"enum": [0, 100, 200, 300, 400, 500]},
                    "reducedMotionFallback": {"enum": ["none", "opacity-only", "static"]},
                },
            },
            "node": {
                "type": "object", "additionalProperties": False,
                "required": ["id", "type", "content", "motion"],
                "properties": {
                    "id": {"type": "string", "pattern": "^[a-z0-9-]+$"},
                    "type": {"enum": sorted(sections)},
                    "content": {"type": "object"},
                    "motion": {"$ref": "#/definitions/motion"},
                    "retrievalEligible": {"type": "boolean"},
                },
                "allOf": branches,
            },
            "assetRole": {"enum": sorted(assets["roles"])},
        },
    }
    return schema


if __name__ == "__main__":
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("schema up to date" if ok else "schema OUT OF DATE")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print("wrote", os.path.relpath(OUT, DR))
